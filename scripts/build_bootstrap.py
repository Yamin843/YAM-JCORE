#!/usr/bin/env python3
"""
build_bootstrap.py — generate Generated/prelude_js.h and
Generated/bootstrap_js.h from scripts/prelude.js and
scripts/bootstrap.js + scripts/lib/*.js.

The bootstrap.js file contains a single marker {{LIBS}}, which is
replaced by the ordered concatenation of the lib files. Concatenation
order matters: util.js must precede anything that uses its helpers,
bridge_probe.js must precede anything that reads bridgeInfo, and
dispatcher.js must be last because it registers the recv("cmd")
handler after all handlers have been added to the `handlers` map.

There are no size limits anywhere in this script: each file is read
whole, concatenated whole, and emitted whole.
"""

import re
import sys
from pathlib import Path

# ── Configuration ─────────────────────────────────────────────

ROOT         = Path(__file__).resolve().parent.parent
SCRIPTS_DIR  = ROOT / "scripts"
LIBS_DIR     = SCRIPTS_DIR / "lib"
GEN_DIR      = ROOT / "app" / "src" / "main" / "jni" / "Generated"

# Concatenation order. util.js first, dispatcher.js last.
LIB_ORDER = [
    "util",
    "send_auto",
    "bridge_probe",
    "handle_mgr",
    "hook_mgr",
    "art_info",
    "jvmti_ops",
    "heap_ops",
    "backtrace_ops",
    "class_ops",
    "hook_ops",
    "call_ops",
    "field_ops",
    "handle_ops",
    "convert_ops",
    "java_api",
    "dispatcher",
]

PRELUDE_IN  = SCRIPTS_DIR / "prelude.js"
BOOTSTRAP_IN = SCRIPTS_DIR / "bootstrap.js"
PRELUDE_OUT = GEN_DIR / "prelude_js.h"
BOOTSTRAP_OUT = GEN_DIR / "bootstrap_js.h"

PRELUDE_NS   = "yamgg_prelude"
PRELUDE_GUARD = "YAMGG_YAMGG_PRELUDE_H"
PRELUDE_DELIM = "YAMJS_PRELUDE"

BOOTSTRAP_NS    = "yamgg_bootstrap"
BOOTSTRAP_GUARD = "YAMGG_YAMGG_BOOTSTRAP_H"
BOOTSTRAP_DELIM = "YAMJS_BOOTSTRAP"

# ── Helpers ──────────────────────────────────────────────────

def read_text(path: Path) -> str:
    if not path.exists():
        print(f"ERROR: input missing: {path}", file=sys.stderr)
        sys.exit(1)
    return path.read_text(encoding="utf-8")


def verify_no_terminator(src: str, delim: str) -> None:
    term = ")" + delim + '"'
    if term in src:
        print(f"ERROR: terminator {term!r} appears in input", file=sys.stderr)
        sys.exit(1)


def verify_no_nul(src: str) -> None:
    if "\x00" in src:
        print("ERROR: NUL byte in input", file=sys.stderr)
        sys.exit(1)


def concatenate_libs() -> str:
    if not LIBS_DIR.is_dir():
        print(f"ERROR: libs directory missing: {LIBS_DIR}", file=sys.stderr)
        sys.exit(1)

    parts: list[str] = []
    for name in LIB_ORDER:
        path = LIBS_DIR / f"{name}.js"
        if not path.exists():
            print(f"ERROR: missing lib: {path}", file=sys.stderr)
            sys.exit(1)
        content = read_text(path)
        verify_no_nul(content)
        parts.append(f"// ═══════════════════════════════════════════════════════════════════\n"
                     f"//  lib/{name}.js\n"
                     f"// ═══════════════════════════════════════════════════════════════════\n\n"
                     f"{content.rstrip()}\n\n")

    # Ensure every file in libs/ is accounted for; warn on extras.
    present = {p.stem for p in LIBS_DIR.glob("*.js")}
    expected = set(LIB_ORDER)
    extra = present - expected
    if extra:
        print(f"WARN: ignoring extra libs: {sorted(extra)}", file=sys.stderr)

    return "".join(parts).rstrip() + "\n"


def assemble_bootstrap() -> str:
    wrapper = read_text(BOOTSTRAP_IN)
    if "{{LIBS}}" not in wrapper:
        print("ERROR: bootstrap.js must contain {{LIBS}} marker",
              file=sys.stderr)
        sys.exit(1)
    libs = concatenate_libs()
    return wrapper.replace("{{LIBS}}", libs, 1)


def emit_header(src: str, out_path: Path, ns: str, guard: str,
                delim: str, source_path: Path) -> None:
    verify_no_nul(src)
    verify_no_terminator(src, delim)

    header = []
    header.append("// Auto-generated by scripts/build_bootstrap.py — do not edit.\n")
    header.append(f"// Source: {source_path.relative_to(ROOT)}\n")
    header.append("// Regenerate: python3 scripts/build_bootstrap.py\n")
    header.append("\n")
    header.append(f"#ifndef {guard}\n")
    header.append(f"#define {guard}\n")
    header.append("\n")
    header.append(f"namespace {ns} {{\n\n")
    header.append(f'static const char kSource[] = R"{delim}(\n')
    header.append(src)
    if not src.endswith("\n"):
        header.append("\n")
    header.append(")" + delim + '";\n')
    header.append("\n")
    header.append(f"}} // namespace {ns}\n")
    header.append("\n")
    header.append(f"#endif // {guard}\n")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("".join(header), encoding="utf-8")

    print(f"✓ {out_path.relative_to(ROOT)} ({len(src):>6} bytes of JS)")


def main() -> int:
    print("build_bootstrap.py")
    print(f"  ROOT      = {ROOT}")
    print(f"  LIBS_DIR  = {LIBS_DIR}")
    print(f"  GEN_DIR   = {GEN_DIR}")
    print()

    prelude_src = read_text(PRELUDE_IN)
    emit_header(
        prelude_src,
        PRELUDE_OUT,
        PRELUDE_NS,
        PRELUDE_GUARD,
        PRELUDE_DELIM,
        PRELUDE_IN,
    )

    bootstrap_src = assemble_bootstrap()
    emit_header(
        bootstrap_src,
        BOOTSTRAP_OUT,
        BOOTSTRAP_NS,
        BOOTSTRAP_GUARD,
        BOOTSTRAP_DELIM,
        BOOTSTRAP_IN,
    )

    print()
    print("Done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
