#!/usr/bin/env python3
"""
dex_to_header.py — embed a .dex file as a C array header.

The header declares two symbols inside namespace yamgg:

    extern const unsigned int  kDexSize;
    extern const unsigned char kDexBytes[];

Both are `static` to give the compiler internal linkage in the
translation unit that includes the header — which matches
native/dex_loader.cpp's single-user contract.

There is NO size limit: the array grows to fit whatever DEX is passed
in. A 100 MB DEX produces a 100 MB C array. Compile time grows linearly,
but correctness is preserved.
"""
import sys
from pathlib import Path


def emit_header(in_path: Path, out_path: Path, namespace: str) -> None:
    if not in_path.exists():
        print(f"ERROR: input missing: {in_path}", file=sys.stderr)
        sys.exit(1)

    data = in_path.read_bytes()
    if not data:
        print(f"ERROR: input is empty: {in_path}", file=sys.stderr)
        sys.exit(1)

    # Sanity check: valid DEX files start with "dex\n".
    if not data.startswith(b"dex\n"):
        print(f"ERROR: {in_path} is not a DEX file (missing magic)",
              file=sys.stderr)
        sys.exit(1)

    guard = "YAMGG_" + namespace.upper() + "_H"

    out_path.parent.mkdir(parents=True, exist_ok=True)

    with out_path.open("w", encoding="utf-8") as f:
        f.write("// Auto-generated by scripts/dex_to_header.py — do not edit.\n")
        f.write(f"// Source: {in_path}\n")
        f.write(f"// Size:   {len(data)} bytes\n")
        f.write("// Regenerate: ./scripts/build_dex.sh\n")
        f.write("\n")
        f.write(f"#ifndef {guard}\n")
        f.write(f"#define {guard}\n")
        f.write("\n")
        f.write("#include <cstddef>\n")
        f.write("\n")
        f.write(f"namespace {namespace} {{\n\n")
        f.write(f"static const unsigned int kDexSize = {len(data)}u;\n\n")
        f.write("static const unsigned char kDexBytes[] = {\n")

        # Emit 16 bytes per line for readability and to keep any single
        # line short enough that even the most conservative compiler is
        # happy. There is no per-line limit that affects correctness.
        bytes_per_line = 16
        for offset in range(0, len(data), bytes_per_line):
            chunk = data[offset:offset + bytes_per_line]
            hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
            if offset + bytes_per_line < len(data):
                f.write(f"    {hex_bytes},\n")
            else:
                f.write(f"    {hex_bytes}\n")

        f.write("};\n\n")
        f.write(f"}} // namespace {namespace}\n")
        f.write("\n")
        f.write(f"#endif // {guard}\n")

    print(f"✓ Generated {out_path}")
    print(f"  size:   {len(data):>10} bytes")
    print(f"  arrays: {(len(data) + bytes_per_line - 1) // bytes_per_line} lines")


def main() -> int:
    if len(sys.argv) != 3:
        print("Usage: dex_to_header.py <input.dex> <output.h>", file=sys.stderr)
        return 1
    in_path  = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    emit_header(in_path, out_path, "yamgg")
    return 0


if __name__ == "__main__":
    sys.exit(main())
